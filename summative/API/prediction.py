"""Early-Career Developer Salary API.

Routes:
  POST /predict  -> predicted annual salary for one developer
  POST /retrain  -> upload a CSV of new rows; the model keeps learning from them
  GET  /docs     -> Swagger UI (generated by FastAPI)
"""
import copy
import io
from pathlib import Path
from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field, ValidationError
from sklearn.metrics import mean_squared_error

# ---------------------------------------------------------------------------
# Model loading (from the repository at startup)
# ---------------------------------------------------------------------------
MODEL_PATH = Path(__file__).parent / "best_model.pkl"
state = {"model": joblib.load(MODEL_PATH)}

NUMERIC_COLUMNS = ["WorkExp", "YearsCode"]
CATEGORICAL_COLUMNS = ["Country", "EdLevel", "OrgSize", "WorkArrangement", "DevType", "ICorPM"]
FEATURE_COLUMNS = NUMERIC_COLUMNS + CATEGORICAL_COLUMNS
TARGET_COLUMN = "salary_k"      # annual salary in thousands of USD
RETRAIN_EPOCHS = 5              # passes over the uploaded rows
MAX_UPLOAD_BYTES = 5_000_000


# ---------------------------------------------------------------------------
# Request / response schemas (types and ranges are enforced by Pydantic)
# ---------------------------------------------------------------------------
class SalaryInput(BaseModel):
    WorkExp: float = Field(..., ge=0, le=15, description="Years of professional work experience (0-15)")
    YearsCode: float = Field(..., ge=0, le=40, description="Years of coding experience in total (0-40)")
    Country: Literal[
        "Brazil", "Canada", "France", "Germany", "India", "Italy",
        "Netherlands", "Poland", "Spain", "UK", "USA", "Ukraine",
    ] = Field(..., description="Country of residence")
    EdLevel: Literal[
        "Primary", "Secondary", "Some college", "Associate",
        "Bachelor", "Master", "Professional", "Other",
    ] = Field(..., description="Highest level of education")
    OrgSize: Literal[
        "Just me", "Under 20", "20-99", "100-499", "500-999",
        "1000-4999", "5000-9999", "10000+", "Unknown",
    ] = Field(..., description="Number of employees at the company")
    WorkArrangement: Literal["Remote", "Hybrid", "In-person", "Flexible"] = Field(
        ..., description="Where the person works"
    )
    DevType: Literal[
        "Architect", "Back-end", "Desktop/Enterprise", "DevOps", "Embedded",
        "Front-end", "Full-stack", "Mobile", "Other",
    ] = Field(..., description="Main developer role")
    ICorPM: Literal["IC", "Manager"] = Field(
        ..., description="IC = individual contributor, Manager = people manager"
    )

    model_config = {
        "json_schema_extra": {
            "example": {
                "WorkExp": 3, "YearsCode": 10, "Country": "Canada", "EdLevel": "Bachelor",
                "OrgSize": "Under 20", "WorkArrangement": "Remote",
                "DevType": "Front-end", "ICorPM": "IC",
            }
        }
    }


class PredictionOut(BaseModel):
    predicted_salary_k: float = Field(..., description="Predicted annual salary, thousands of USD")
    predicted_salary_usd: float = Field(..., description="Predicted annual salary, USD")


# ---------------------------------------------------------------------------
# App and CORS
# ---------------------------------------------------------------------------
app = FastAPI(
    title="Early-Career Developer Salary API",
    description="Estimates the annual salary of a young developer from the Stack Overflow "
                "Developer Survey 2025. Use /predict to get an estimate and /retrain to "
                "update the model with new data.",
)

# CORS decides which WEBSITES may call this API from a browser.
# ALLOWED: only the origins listed below (the deployed Render URL, and the local
#   addresses used while developing a Flutter web build or a local page).
# RESTRICTED: every other website, because the wildcard "*" is not used, so a random
#   site cannot make a visitor's browser call this API.
# Methods: only GET and POST, because the API has no other operations.
# Headers: only Content-Type and Accept, the two the app needs to send JSON.
# Credentials: False, because the API uses no cookies or logins, so browsers have no
#   reason to send them.
# A Flutter mobile app is not a browser, so CORS does not affect it.
RENDER_URL = "https://linear-regression-model-ikuw.onrender.com"
ALLOWED_ORIGINS = [
    RENDER_URL,
    "http://localhost:5000",    # Flutter web debug: flutter run -d chrome --web-port 5000
    "http://127.0.0.1:5000",
    "http://localhost:8000",    # local API docs page
    "http://127.0.0.1:8000",
]

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=False,
)


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------
@app.get("/", include_in_schema=False)
def root():
    return {"message": "Early-Career Developer Salary API. See /docs for the interactive docs."}


@app.post("/predict", response_model=PredictionOut)
def predict(data: SalaryInput):
    """Predict the annual salary for one developer."""
    row = pd.DataFrame([data.model_dump()])[FEATURE_COLUMNS]
    prediction_k = float(state["model"].predict(row)[0])
    prediction_k = max(prediction_k, 0.0)       # a salary cannot be negative
    return PredictionOut(
        predicted_salary_k=round(prediction_k, 2),
        predicted_salary_usd=round(prediction_k * 1000, 0),
    )


@app.post("/retrain")
async def retrain(file: UploadFile = File(..., description="CSV with the 8 feature columns plus salary_k")):
    """Upload a CSV of new rows. The model continues training on them and is used right away."""
    if not (file.filename or "").lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file.")

    content = await file.read()
    if len(content) > MAX_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail="File too large (limit 5 MB).")
    try:
        new_data = pd.read_csv(io.BytesIO(content))
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read the file as a CSV.")

    # 1. The CSV must have the same columns as the training data
    needed = FEATURE_COLUMNS + [TARGET_COLUMN]
    missing = [c for c in needed if c not in new_data.columns]
    if missing:
        raise HTTPException(status_code=422, detail=f"Missing columns: {missing}. Required: {needed}")
    if new_data.empty:
        raise HTTPException(status_code=422, detail="The CSV has no rows.")

    # 2. Every row must pass the same validation as /predict
    problems, valid_rows = [], []
    for i, record in enumerate(new_data[FEATURE_COLUMNS].to_dict("records")):
        record = {k: (v.strip() if isinstance(v, str) else v) for k, v in record.items()}
        try:
            valid_rows.append(SalaryInput.model_validate(record).model_dump())
        except ValidationError as err:
            first = err.errors()[0]
            problems.append(f"row {i + 2}: {first['loc'][0]} - {first['msg']}")
    salary = pd.to_numeric(new_data[TARGET_COLUMN], errors="coerce")
    for i in salary[~salary.between(0.001, 1000)].index:      # NaN also fails this test
        problems.append(f"row {i + 2}: {TARGET_COLUMN} must be a number between 0 and 1000 (thousands USD)")
    if problems:
        raise HTTPException(
            status_code=422,
            detail={"message": f"{len(problems)} problem(s) found. Nothing was changed.",
                    "first_problems": problems[:10]},
        )

    X_new = pd.DataFrame(valid_rows)[FEATURE_COLUMNS]
    y_new = salary.astype(float)

    # 3. Continue training the saved SGDRegressor with partial_fit (on a copy, so a failure
    #    can never leave a half-updated model in use)
    candidate = copy.deepcopy(state["model"])
    preprocess, estimator = candidate.named_steps["preprocess"], candidate.named_steps["model"]
    if not hasattr(estimator, "partial_fit"):
        raise HTTPException(status_code=501, detail="The saved model cannot learn incrementally.")

    X_new_processed = preprocess.transform(X_new)          # keeps the original scaling/encoding
    mse_before = mean_squared_error(y_new, estimator.predict(X_new_processed))
    for _ in range(RETRAIN_EPOCHS):
        estimator.partial_fit(X_new_processed, y_new)
    mse_after = mean_squared_error(y_new, estimator.predict(X_new_processed))

    # 4. Start using the updated model immediately (no redeploy needed)
    state["model"] = candidate
    try:
        joblib.dump(candidate, MODEL_PATH)       # survives restarts until Render's free plan resets files
        saved = True
    except OSError:
        saved = False

    return {
        "message": "Model updated and now used by /predict.",
        "rows_used": int(len(X_new)),
        "epochs": RETRAIN_EPOCHS,
        "mse_on_new_rows_before": round(mse_before, 1),
        "mse_on_new_rows_after": round(mse_after, 1),
        "saved_to_disk": saved,
    }